-- 6. 평가 / 리뷰
CREATE TABLE track_ratings
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    track_id      BIGINT      NOT NULL REFERENCES tracks (id),
    score         INT         NOT NULL CHECK (
        score >= 1
            AND score <= 10
        ),
    source        TEXT NULL,
    review        VARCHAR(1000) NULL,
    is_public     BOOLEAN     NOT NULL DEFAULT TRUE,
    review_status TEXT        NOT NULL DEFAULT 'NORMAL',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, track_id) -- 한 사용자는 트랙당 하나의 평가
);

CREATE TABLE album_ratings
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    album_id      BIGINT      NOT NULL REFERENCES albums (id),
    score         INT         NOT NULL CHECK (
        score >= 1
            AND score <= 10
        ),
    review        VARCHAR(1000) NULL,
    is_public     BOOLEAN     NOT NULL DEFAULT TRUE,
    review_status TEXT        NOT NULL DEFAULT 'NORMAL',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, album_id) -- 한 사용자는 앨범당 하나의 평가
);

-- 리뷰(평가)에 대한 좋아요: 트랙 리뷰 또는 앨범 리뷰 중 하나만 지정
CREATE TABLE review_likes
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    track_rating_id BIGINT NULL REFERENCES track_ratings (id),
    album_rating_id BIGINT NULL REFERENCES album_ratings (id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        num_nonnulls(track_rating_id, album_rating_id) = 1
        )
);

CREATE UNIQUE INDEX uq_review_likes_track ON review_likes (user_id, track_rating_id) WHERE
	track_rating_id IS NOT NULL;

CREATE UNIQUE INDEX uq_review_likes_album ON review_likes (user_id, album_rating_id) WHERE
	album_rating_id IS NOT NULL;

CREATE TABLE review_stats
(
    rating_type TEXT        NOT NULL, -- 'TRACK' / 'ALBUM'
    rating_id   BIGINT      NOT NULL,
    like_count  INT         NOT NULL DEFAULT 0,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (rating_type, rating_id)
);

CREATE TABLE user_stats
(
    user_id                 BIGINT PRIMARY KEY REFERENCES users (id),
    rating_count            INT         NOT NULL DEFAULT 0,
    rating_sum              BIGINT      NOT NULL DEFAULT 0,
    album_rating_count      INT         NOT NULL DEFAULT 0,
    review_count            INT         NOT NULL DEFAULT 0,
    follower_count          INT         NOT NULL DEFAULT 0,
    following_count         INT         NOT NULL DEFAULT 0,
    recommended_track_count INT         NOT NULL DEFAULT 0,
    hit_rating_count        INT         NOT NULL DEFAULT 0,
    hit_rating_sum          BIGINT      NOT NULL DEFAULT 0,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 7. 태그
CREATE TABLE tags
(
