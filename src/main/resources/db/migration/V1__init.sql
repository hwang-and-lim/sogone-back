    name             VARCHAR(30) NOT NULL UNIQUE,
    is_official      BOOLEAN     NOT NULL DEFAULT FALSE,
    category         TEXT NULL,
    status           TEXT        NOT NULL DEFAULT 'ACTIVE',
    user_id          BIGINT NULL REFERENCES users (id), -- 공식 태그는 생성자가 없을 수 있음
