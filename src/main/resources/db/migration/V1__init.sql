    user_count   INT         NOT NULL DEFAULT 0,
    last_used_at TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (tag_id, genre_id)
);

-- 8. 커뮤니티 (게시글, 댓글)
CREATE TABLE posts
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id),
    type           TEXT         NOT NULL,
    genre_id       BIGINT       NOT NULL REFERENCES genres (id),
    genre_auto     BOOLEAN      NOT NULL DEFAULT TRUE,
    title          VARCHAR(150) NOT NULL,
    body           TEXT         NOT NULL,
    status         TEXT         NOT NULL DEFAULT 'NORMAL',
    like_count     INT          NOT NULL DEFAULT 0,
    comment_count  INT          NOT NULL DEFAULT 0,
    wishlist_count INT          NOT NULL DEFAULT 0,
    hot_score      REAL         NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ NULL
);

-- 게시글에 첨부된 트랙/앨범: 둘 중 하나만 지정
CREATE TABLE post_tracks
(
    post_id      BIGINT NOT NULL REFERENCES posts (id),
    position     INT    NOT NULL CHECK (
        position >= 1
            AND position <= 10
        ),
    track_id     BIGINT NULL REFERENCES tracks (id),
    album_id     BIGINT NULL REFERENCES albums (id),
    author_score INT NULL,
    PRIMARY KEY (post_id, position),
    CHECK (num_nonnulls(track_id, album_id) = 1)
);

CREATE TABLE post_tags
(
    post_id BIGINT NOT NULL REFERENCES posts (id),
    tag_id  BIGINT NOT NULL REFERENCES tags (id),
    PRIMARY KEY (post_id, tag_id)
);

CREATE TABLE post_likes
(
    post_id    BIGINT      NOT NULL REFERENCES posts (id),
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
