-- 1. 사용자 / 인증
CREATE TABLE users
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname          VARCHAR(30) NOT NULL UNIQUE,
    profile_image_url TEXT NULL,
    bio               VARCHAR(150) NULL,
    role              TEXT        NOT NULL DEFAULT 'USER',
    status            TEXT        NOT NULL DEFAULT 'ACTIVE',
    onboarded_at      TIMESTAMPTZ NULL,
    last_active_at    TIMESTAMPTZ NULL,
    restricted_until  TIMESTAMPTZ NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at        TIMESTAMPTZ NULL
);

CREATE TABLE user_credentials
(
    user_id             BIGINT PRIMARY KEY REFERENCES users (id),
    login_email         VARCHAR(255) NOT NULL UNIQUE,
    hashed_password     TEXT         NOT NULL,
    email_verified_at   TIMESTAMPTZ NULL,
    password_changed_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    failed_login_count  INT          NOT NULL DEFAULT 0,
    locked_until        TIMESTAMPTZ NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE user_auth_providers
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id),
    provider         TEXT         NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    email            VARCHAR(255) NULL,
    refresh_token    TEXT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (provider, provider_user_id)
);

CREATE TABLE password_reset_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    purpose    TEXT        NOT NULL,
    token_hash CHAR(64)    NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_settings
(
    user_id      BIGINT PRIMARY KEY REFERENCES users (id),
    push_enabled BOOLEAN     NOT NULL DEFAULT TRUE,
    push_like    BOOLEAN     NOT NULL DEFAULT TRUE,
    push_comment BOOLEAN     NOT NULL DEFAULT TRUE,
    push_follow  BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_push_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    platform   TEXT        NOT NULL,
    token      TEXT        NOT NULL UNIQUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_sessions
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT      NOT NULL REFERENCES users (id),
    refresh_token_hash CHAR(64)    NOT NULL UNIQUE,
    platform           TEXT        NOT NULL CHECK (platform IN ('IOS', 'ANDROID', 'WEB')),
    device_name        VARCHAR(100) NULL,
    expires_at         TIMESTAMPTZ NOT NULL,
    last_used_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at         TIMESTAMPTZ NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 사용자 관계 (팔로우, 차단)
CREATE TABLE user_follows
(
    follower_id BIGINT      NOT NULL REFERENCES users (id),
    followee_id BIGINT      NOT NULL REFERENCES users (id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id),
    CHECK (follower_id <> followee_id)
);

CREATE TABLE user_blocks
(
    blocker_id BIGINT      NOT NULL REFERENCES users (id),
    blocked_id BIGINT      NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);

-- 3. 음악 카탈로그 (장르, 아티스트, 앨범, 트랙)
CREATE TABLE genres
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT NULL REFERENCES genres (id), -- 최상위 장르는 NULL
    name       VARCHAR(50) NOT NULL,
    slug       VARCHAR(50) NOT NULL UNIQUE,
    sort_order INT         NOT NULL,
    is_active  BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE genre_apple_map
(
    apple_genre_id   VARCHAR(32) PRIMARY KEY,
    apple_genre_name VARCHAR(100) NOT NULL,
    genre_id         BIGINT       NOT NULL REFERENCES genres (id)
);

CREATE TABLE artists
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primary_genre_id BIGINT       NOT NULL REFERENCES genres (id),
    apple_id         VARCHAR(32)  NOT NULL UNIQUE,
    name             VARCHAR(255) NOT NULL,
    artwork_url      TEXT NULL,
    apple_url        TEXT NULL,
    synced_at        TIMESTAMPTZ  NOT NULL,
    available        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE albums
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primary_genre_id    BIGINT       NOT NULL REFERENCES genres (id),
    apple_id            VARCHAR(32)  NOT NULL UNIQUE,
    upc                 VARCHAR(20) NULL,
    title               VARCHAR(500) NOT NULL,
    artist_display_name VARCHAR(500) NOT NULL,
    release_date        DATE NULL,
    record_label        VARCHAR(255) NULL,
    copyright           TEXT NULL,
    track_count         INT NULL,
    is_single           BOOLEAN      NOT NULL DEFAULT FALSE,
    artwork_url         TEXT NULL,
    artwork_bg_color    CHAR(6) NULL,
    apple_url           TEXT NULL,
    synced_at           TIMESTAMPTZ  NOT NULL,
    available           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE tracks
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id            BIGINT       NOT NULL REFERENCES albums (id),
    apple_id            VARCHAR(32)  NOT NULL UNIQUE,
    isrc                CHAR(12) NULL,
    title               VARCHAR(500) NOT NULL,
    artist_display_name VARCHAR(500) NOT NULL,
    duration_ms         INT NULL,
    disc_number         INT NULL,
    track_number        INT NULL,
    composer            TEXT NULL,
    content_rating      TEXT NULL,
    release_date        DATE NULL,
    preview_url         TEXT NULL,
    apple_url           TEXT NULL,
    synced_at           TIMESTAMPTZ  NOT NULL,
    available           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE album_artists
(
    album_id  BIGINT NOT NULL REFERENCES albums (id),
    artist_id BIGINT NOT NULL REFERENCES artists (id),
    position  INT    NOT NULL,
    PRIMARY KEY (album_id, artist_id)
);

CREATE TABLE track_artists
(
    track_id  BIGINT NOT NULL REFERENCES tracks (id),
    artist_id BIGINT NOT NULL REFERENCES artists (id),
    role      TEXT NULL DEFAULT 'MAIN',
    position  INT    NOT NULL,
    PRIMARY KEY (track_id, artist_id)
);

CREATE TABLE track_genres
(
    track_id   BIGINT  NOT NULL REFERENCES tracks (id),
    genre_id   BIGINT  NOT NULL REFERENCES genres (id),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (track_id, genre_id)
);

